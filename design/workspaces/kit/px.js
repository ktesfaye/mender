Object.assign(PX, window.PX_EXTRA || {});
function pxIcon(name, color, size) {
  const m = PX[name];
  let r = '';
  m.forEach((row, y) => [...row].forEach((c, x) => { if (c === '#') r += `<rect x="${x}" y="${y}" width="1" height="1"/>`; }));
  return `<svg viewBox="0 0 9 9" width="${size}" height="${size}" shape-rendering="crispEdges" fill="${color}">${r}</svg>`;
}
document.querySelectorAll('i[data-px]').forEach((el) => {
  el.innerHTML = pxIcon(el.dataset.px, el.dataset.c || 'currentColor', +(el.dataset.s || 18));
});
